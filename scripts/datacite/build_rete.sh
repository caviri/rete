#!/usr/bin/env bash
# DataCite Parquet -> datacite.rete, the faithful build (run INSIDE rete-dev).
#
#   bash scripts/datacite/build_rete.sh ROOT OUT_DIR [BUDGET_MB] [WORKERS] [SPILL_DIR]
#
#   ROOT     the Parquet root: parquet-2023/ -2024/ -2025/ and parquet-links-2023/ -may2025/
#   OUT_DIR  receives plan.parquet(+.json), datacite.tally.json, datacite.rete, build logs
#
# Needs python3 with pyarrow, duckdb and pyoxigraph, and a `rete` on PATH (or $RETE).
# Steps: (1) R9/R10 record plan with DuckDB; (2) the converter streams N-Triples,
# checking every IRI with oxiri and writing the rule tally; (3) `rete build --strict`
# refuses any IRI the N-Triples grammar or RFC 3987 rejects, within BUDGET_MB of RAM.
# The Dataset Card comes from scripts/datacite/cards/datacite.card.json, generated by
# make_metadata.py --tally from a previous run's tally (the converter is deterministic).
set -euo pipefail
ROOT=${1:?parquet root}; OUT=${2:?output dir}; BUDGET=${3:-14000}; WORKERS=${4:-10}
SPILL=${5:-/tmp/datacite-spill}
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RETE=${RETE:-rete}
mkdir -p "$OUT" "$SPILL"

if [ ! -f "$OUT/plan.parquet" ]; then
  python3 "$HERE/parquet_to_nt.py" plan --root "$ROOT" --out "$OUT/plan.parquet"
fi

{ cat "$HERE/datacite-ontology.nt"
  python3 "$HERE/parquet_to_nt.py" emit --root "$ROOT" --plan "$OUT/plan.parquet" \
    --report "$OUT/datacite.tally.json" --workers "$WORKERS" 2> "$OUT/convert.log"
} | "$RETE" build - --format nt --strict --memory-budget-mb "$BUDGET" --tmp-dir "$SPILL" \
      -o "$OUT/datacite.rete" --card-file "$HERE/cards/datacite.card.json" --no-card-costs
