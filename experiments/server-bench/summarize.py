"""Fold results/ into results/summary.json and the landing's servers.js.

Usage: python summarize.py [path/to/site/landing/servers.js]

servePeakBytes is the larger of getrusage's ru_maxrss for the server process
(read when it stopped) and its VmHWM read after the last question.
answerBytes is the mean response size over the graph's questions.
"""
import json
import os
import statistics
import sys

ENGINES = [
    {"key": "qlever", "name": "QLever", "version": "commit 18c097c (2026-11-14)",
     "image": "adfreiburg/qlever@sha256:d7ecda47b4d0132c190b4a73279761fd1c614f24cba4e894ca1ba8117cef6727"},
    {"key": "oxigraph", "name": "Oxigraph", "version": "0.5.13",
     "image": "ghcr.io/oxigraph/oxigraph@sha256:260454ee29c091d2cdb99dd156212594ff3127850627adb4cfdcd9b1e425d480"},
]
GRAPHS = ["linked-jazz", "bph", "davidrumsey", "hugging-face"]
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def kib(s, field):
    for part in s.split("kB"):
        if field in part:
            return int(part.split(field + ":")[1].strip())
    return 0


summary = {"measured": "2026-11-15", "machine": "Docker, 2 CPUs and 4 GB per engine", "engines": ENGINES, "graphs": {}}
for g in GRAPHS:
    summary["graphs"][g] = {}
    for e in ENGINES:
        k = e["key"]
        build, serve, snap, qs = (load(f"{k}-{g}-{x}.json") for x in ("build", "serve", "serve-snap", "queries"))
        idx = os.path.join(R, f"{k}-{g}-index.txt")
        row = {"built": bool(build and build["exit"] == 0)}
        if build:
            row.update(buildSeconds=build["wall_s"], buildPeakBytes=build["maxrss_kib"] * 1024, buildExit=build["exit"])
        if row["built"] and os.path.exists(idx):
            row["indexBytes"] = int(open(idx).readline())
        if row["built"] and serve and snap and qs and all("error" not in q["first"] for q in qs):
            row["readySeconds"] = snap["ready_s"]
            row["servePeakBytes"] = max(serve["maxrss_kib"], kib(snap["after"], "VmHWM")) * 1024
            row["questions"] = [{"label": q["label"], "firstMs": round(q["first"]["ms"], 1), "medianMs": round(q["median_ms"], 1),
                                 "rows": q["first"]["rows"], "bytes": q["first"]["bytes"]} for q in qs]
            row["answerBytes"] = round(statistics.mean(q["first"]["bytes"] for q in qs))
        elif qs:
            row["errors"] = [q["first"].get("error") for q in qs if "error" in q["first"]]
        summary["graphs"][g][k] = row

json.dump(summary, open(os.path.join(R, "summary.json"), "w"), indent=1)

if len(sys.argv) > 1:
    keep = ("indexBytes", "servePeakBytes", "answerBytes", "buildSeconds", "readySeconds", "questions")
    data = {g: {k: {f: v[f] for f in keep if f in v} for k, v in m.items() if "servePeakBytes" in v}
            for g, m in summary["graphs"].items()}
    js = (
        "// Generated by experiments/server-bench/summarize.py. QLever and Oxigraph, each in Docker with\n"
        "// 2 CPUs and 4 GB, built from the same N-Triples (rete export of the files on R2) and asked the\n"
        "// demo's questions on " + summary["measured"] + ". servePeakBytes is the server's peak resident memory,\n"
        "// indexBytes its files on disk, answerBytes the mean size of an answer.\n"
        f"export const SERVERS_MEASURED = {json.dumps(summary['measured'])};\n"
        f"export const ENGINES = {json.dumps([{x: e[x] for x in ('key', 'name', 'version')} for e in ENGINES])};\n"
        f"export const SERVERS = {json.dumps(data, indent=1)};\n"
    )
    open(sys.argv[1], "w", newline="\n").write(js)
print(json.dumps({g: {k: {f: v.get(f) for f in ("built", "buildSeconds", "buildPeakBytes", "indexBytes", "servePeakBytes", "answerBytes")}
                      for k, v in m.items()} for g, m in summary["graphs"].items()}, indent=1))
