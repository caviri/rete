// The rete file explorer's copy of the graph view
// (experiments/rete-file-explorer/graph/): the same page Claude Desktop shows,
// which the explorer hosts itself — it answers the page's tool calls from the
// archive it has open (js/graph-host.js) instead of from this extension.
//
//   graph-view.html  the view page, as build.mjs makes it for the extension
//   host-lib.js      the host's half: the MCP Apps AppBridge and the view's
//                    model (src/view-model.mjs), one ES module
//   BUILD.json       the version stamped into both
//
// They are generated and committed (the explorer has no build step, and the
// desktop app stages the explorer's files as they are). Regenerate after
// changing src/view/ or src/view-model.mjs:
//
//   docker run --rm -v "$PWD":/w -w /w/clients/mcpb node:22-slim \
//     sh -c 'npm ci --no-audit --no-fund --silent && node build-explorer.mjs'
//
// `--check` rebuilds them in memory and fails if the committed copies differ.
// It builds with the version they carry, so a release's version bump alone is
// not a difference.
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { aboutOf, buildViewHtml, here, repo, workspaceVersion } from "./view-build.mjs";

const out = join(repo, "experiments", "rete-file-explorer", "graph");
const check = process.argv.includes("--check");
const stampFile = join(out, "BUILD.json");
const version = check && existsSync(stampFile) ? JSON.parse(readFileSync(stampFile, "utf8")).version : workspaceVersion();

// No commit or date in the stamp: the files are committed, and a stamp that
// changed on every build would make every regeneration a diff.
const about = aboutOf({ version, build: { commit: null, date: null, label: "in the rete file explorer" } });
about.data = "Every published graph has its own licence and source; its card says which. Credit them when using the data.";

const banner = "// Generated by clients/mcpb/build-explorer.mjs — do not edit; see that file.";
const html = (await buildViewHtml(about)).replace("<!doctype html>", `<!doctype html>\n<!-- ${banner.slice(3)} -->`);
const lib = await build({
  stdin: {
    contents: [
      `export { AppBridge, PostMessageTransport } from "@modelcontextprotocol/ext-apps/app-bridge";`,
      `export * from "./src/view-model.mjs";`,
    ].join("\n"),
    resolveDir: here,
    sourcefile: "host-lib.js",
  },
  bundle: true,
  platform: "browser",
  format: "esm",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "eof",
  banner: { js: banner },
});

const files = {
  "graph-view.html": html,
  "host-lib.js": lib.outputFiles[0].text,
  "BUILD.json": `${JSON.stringify({ version, generator: "clients/mcpb/build-explorer.mjs" }, null, 2)}\n`,
};

if (check) {
  const stale = Object.entries(files).filter(([name, text]) => !existsSync(join(out, name)) || readFileSync(join(out, name), "utf8") !== text);
  if (stale.length) {
    console.error(
      `the file explorer's copy of the graph view is out of date: ${stale.map(([n]) => n).join(", ")}\n` +
        "regenerate it with: (cd clients/mcpb && node build-explorer.mjs), and commit experiments/rete-file-explorer/graph/",
    );
    process.exit(1);
  }
  console.log(`the file explorer's copy of the graph view is current (version ${version})`);
} else {
  mkdirSync(out, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text);
  const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
  console.log(`wrote ${out} (version ${version})`);
  for (const [name, text] of Object.entries(files)) console.log(`  ${name.padEnd(16)} ${kb(text)}`);
}
