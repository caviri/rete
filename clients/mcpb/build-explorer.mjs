// The committed copies of the graph view: the same page Claude Desktop shows,
// for the two hosts that serve it without building it.
//
// The rete file explorer (experiments/rete-file-explorer/graph/) hosts the
// page itself — it answers the page's tool calls from the archive it has open
// (js/graph-host.js) instead of from this extension:
//
//   graph-view.html  the view page, as build.mjs makes it for the extension
//   host-lib.js      the host's half: the MCP Apps AppBridge and the view's
//                    model (src/view-model.mjs), one ES module
//   BUILD.json       the version stamped into both
//
// rete-server (clients/server/rete_server/view/) sends the page to its MCP
// clients as ui://rete/graph-view.html and answers its tool calls with a
// Python port of src/views.mjs (rete_server/views.py):
//
//   graph-view.html  the view page
//   BUILD.json       the version stamped into it
//
// They are generated and committed (the explorer has no build step, the
// desktop app stages the explorer's files as they are, and the server's image
// is built from clients/server alone). Regenerate after changing src/view/ or
// src/view-model.mjs:
//
//   docker run --rm -v "$PWD":/w -w /w/clients/mcpb node:22-slim //     sh -c 'npm ci --no-audit --no-fund --silent && node build-explorer.mjs'
//
// `--check` rebuilds them in memory and fails if the committed copies differ.
// It builds with the version they carry, so a release's version bump alone is
// not a difference.
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { aboutOf, buildViewHtml, here, repo, workspaceVersion } from "./view-build.mjs";

const check = process.argv.includes("--check");
const banner = "// Generated by clients/mcpb/build-explorer.mjs — do not edit; see that file.";
const stamp = (version) => `${JSON.stringify({ version, generator: "clients/mcpb/build-explorer.mjs" }, null, 2)}\n`;
const versionIn = (out) => {
  const file = join(out, "BUILD.json");
  return check && existsSync(file) ? JSON.parse(readFileSync(file, "utf8")).version : workspaceVersion();
};

/** The view page, with the facts its About panel shows. */
async function page(version, label, data) {
  // No commit or date in the stamp: the files are committed, and a stamp that
  // changed on every build would make every regeneration a diff.
  const about = aboutOf({ version, build: { commit: null, date: null, label } });
  if (data) about.data = data;
  return (await buildViewHtml(about)).replace("<!doctype html>", `<!doctype html>\n<!-- ${banner.slice(3)} -->`);
}

async function explorer() {
  const out = join(repo, "experiments", "rete-file-explorer", "graph");
  const version = versionIn(out);
  const lib = await build({
    stdin: {
      contents: [
        `export { AppBridge, PostMessageTransport } from "@modelcontextprotocol/ext-apps/app-bridge";`,
        `export * from "./src/view-model.mjs";`,
      ].join("\n"),
      resolveDir: here,
      sourcefile: "host-lib.js",
    },
    bundle: true,
    platform: "browser",
    format: "esm",
    target: "es2020",
    minify: true,
    write: false,
    legalComments: "eof",
    banner: { js: banner },
  });
  const files = {
    "graph-view.html": await page(
      version,
      "in the rete file explorer",
      "Every published graph has its own licence and source; its card says which. Credit them when using the data.",
    ),
    "host-lib.js": lib.outputFiles[0].text,
    "BUILD.json": stamp(version),
  };
  return { name: "the file explorer's", out, rel: "experiments/rete-file-explorer/graph/", version, files };
}

async function server() {
  const out = join(repo, "clients", "server", "rete_server", "view");
  const version = versionIn(out);
  const files = { "graph-view.html": await page(version, "in rete-server"), "BUILD.json": stamp(version) };
  return { name: "rete-server's", out, rel: "clients/server/rete_server/view/", version, files };
}

let failed = false;
for (const { name, out, rel, version, files } of [await explorer(), await server()]) {
  if (check) {
    const stale = Object.entries(files).filter(([f, text]) => !existsSync(join(out, f)) || readFileSync(join(out, f), "utf8") !== text);
    if (stale.length) {
      console.error(
        `${name} copy of the graph view is out of date: ${stale.map(([f]) => f).join(", ")}\n` +
          `regenerate it with: (cd clients/mcpb && node build-explorer.mjs), and commit ${rel}`,
      );
      failed = true;
    } else console.log(`${name} copy of the graph view is current (version ${version})`);
  } else {
    mkdirSync(out, { recursive: true });
    for (const [f, text] of Object.entries(files)) writeFileSync(join(out, f), text);
    const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
    console.log(`wrote ${out} (version ${version})`);
    for (const [f, text] of Object.entries(files)) console.log(`  ${f.padEnd(16)} ${kb(text)}`);
  }
}
if (failed) process.exit(1);
